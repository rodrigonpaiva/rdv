import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS from 'openapi-typescript';
import { createConfig, lintFromString } from '@redocly/openapi-core';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const sourceFile = path.join(root, 'packages/contracts/openapi/v1.json');

export async function validateDocument(document) {
  // All references must stay in the versioned document; generation never fetches external input.
  function visit(value) {
    if (!value || typeof value !== 'object') return;
    if ('$ref' in value && !value.$ref.startsWith('#/components/')) throw new Error('Only local component references are permitted');
    for (const item of Object.values(value)) visit(item);
  }
  visit(document);
  const config = await createConfig({ rules: { struct: 'error', 'no-unresolved-refs': 'error', 'operation-operationId-unique': 'error', 'operation-operationId': 'error' } });
  const problems = await lintFromString({ source: JSON.stringify(document), absoluteRef: sourceFile, config });
  if (problems.some((problem) => problem.severity === 'error')) {
    throw new Error(`OpenAPI validation failed: ${problems.map((problem) => problem.message).join('; ')}`);
  }
}

async function tree(directory, prefix = '') {
  const result = new Map();
  for (const entry of (await fs.readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const name = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) {
      for (const [key, value] of await tree(path.join(directory, entry.name), name)) result.set(key, value);
    } else result.set(name, await fs.readFile(path.join(directory, entry.name), 'utf8'));
  }
  return result;
}

export async function generate(check = false) {
  const document = JSON.parse(await fs.readFile(sourceFile, 'utf8'));
  await validateDocument(document);
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'agenda-contracts-'));
  const output = path.join(temp, 'generated');
  const target = path.join(root, 'packages/contracts/src/generated');
  try {
    await fs.mkdir(output, { recursive: true });
    const types = await openapiTS(document);
    await fs.writeFile(path.join(output, 'schema.ts'), types);
    await fs.writeFile(path.join(output, 'openapi.ts'), `// Generated by npm run contracts:generate. Do not edit.\nexport const apiDocument = ${JSON.stringify(document, null, 2)} as const;\n`);
    if (check) {
      const actual = await tree(target);
      const expected = await tree(output);
      if (actual.size !== expected.size || [...expected].some(([file, value]) => actual.get(file) !== value)) {
        throw new Error('Generated contracts drifted; run npm run contracts:generate');
      }
    } else {
      await fs.mkdir(target, { recursive: true });
      // Only this owned generated directory is replaced; source files remain untouched.
      for (const entry of await fs.readdir(target)) await fs.rm(path.join(target, entry), { recursive: true });
      await fs.cp(output, target, { recursive: true });
    }
  } finally { await fs.rm(temp, { recursive: true, force: true }); }
  console.log(check ? 'OpenAPI validation and generated-contract drift check passed.' : 'OpenAPI validated; generated contracts updated.');
}

// Resolve macOS /tmp aliases and symlinked entry paths before detecting CLI execution.
if (process.argv[1] && await fs.realpath(process.argv[1]).catch(() => null) === fileURLToPath(import.meta.url)) {
  await generate(process.argv.includes('--check'));
}
